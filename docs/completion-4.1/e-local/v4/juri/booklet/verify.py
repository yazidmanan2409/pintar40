# Verify the booklet PDF against items.json: count, ids in order, every text field present exactly once in
# sequence (whitespace-normalised, since a PDF wraps lines), and no forbidden term.
import json, sys, subprocess, re, hashlib
items_path, pdf_path = sys.argv[1:3]
items = json.load(open(items_path, encoding='utf-8'))
txt = subprocess.run(['pdftotext', '-enc', 'UTF-8', '-nopgbrk', pdf_path, '-'], capture_output=True, text=True, check=True).stdout
# drop running header/footer lines
lines = [l for l in txt.split('\n') if not re.fullmatch(r'\s*(Buku Soal Penilaian · Evaluasi soal PINTAR|Halaman \d+ dari \d+)\s*', l)]
norm = lambda s: re.sub(r'\s+', ' ', s).strip()
T = norm(' '.join(lines))
fails = []
assert len(items) == 60 or print('WARNING: items.json has', len(items), 'items')
ids = [x['item_id'] for x in items]
if len(ids) != len(set(ids)): fails.append('duplicate item_id in items.json')
# ids appear in order, each exactly once as a card heading
pos = 0
for i in ids:
    if T.count(i) < 1: fails.append(f'{i}: missing'); continue
    k = T.find(i, pos)
    if k < 0: fails.append(f'{i}: out of order'); continue
    pos = k
# numbering: 'Soal n kode <id>' for n = 1..60
for n, i in enumerate(ids, 1):
    if f'Soal {n} kode {i}' not in T: fails.append(f'{i}: not numbered {n}')
# every field, in order, within its own card
starts = [T.find(i) for i in ids] + [len(T)]
for n, it in enumerate(items):
    seg = T[starts[n]:starts[n+1]] if starts[n] >= 0 else ''
    fields = [('stem', it['stem'])] + [(f'option {o["label"]}', o['body']) for o in it['options']] + \
             [('key', 'Usulan kunci jawaban: ' + it['key']), ('rationale', it['key_rationale'])] + \
             [f for d in it['distractors'] for f in ((f'misconception {d["label"]}', d['misconception']), (f'code {d["label"]}', d['misconception_code']))]
    p = 0
    for name, val in fields:
        v = norm(val)
        k = seg.find(v, p)
        if k < 0: fails.append(f'{it["item_id"]}: {name} not found verbatim'); continue
        p = k + len(v)
    # option order: A, B, C, D labels as given
    labs = [o['label'] for o in it['options']]
    if labs != sorted(labs): fails.append(f'{it["item_id"]}: option labels not in source order? {labs}')
forbidden = r'anthropic|openai|claude|\bgpt|gemini|sonnet|opus|haiku|\bmodel\b|penyedia|provider|seed|temperature|token|ledger|map\.json|sha256|generated by|dihasilkan oleh'
hits = sorted(set(m.group(0).lower() for m in re.finditer(forbidden, T, re.I)))
if hits: fails.append('forbidden terms: ' + ', '.join(hits))
print('items:', len(items), '| ids unique:', len(set(ids)) == len(ids), '| first/last:', ids[0], ids[-1])
print('pdf sha256:', hashlib.sha256(open(pdf_path, 'rb').read()).hexdigest())
print('items.json sha256:', hashlib.sha256(open(items_path, 'rb').read()).hexdigest())
print('RESULT:', 'PASS' if not fails else 'FAIL'); [print(' -', f) for f in fails[:40]]
sys.exit(1 if fails else 0)
